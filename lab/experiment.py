"""The experiment: does any of this survive the pipeline both corpora share?

Method, stated before the numbers:

  corpus      N authentic frames and N manipulated frames, distinct seeds, same generator
  treatment   every frame through each degradation level in lab.degrade.LEVELS, identically
  measure     four signals per frame, then per level: ROC AUC, and the FP/FN at the best
              Youden threshold
  control     labels shuffled, 200 permutations: an AUC that survives shuffling is a bug

A signal is only interesting if its AUC holds up at "cctv". An AUC of 0.5 at that level means
the signal died in the pipeline, and no amount of threshold tuning brings it back.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from lab import degrade
from lab.signals import all_signals, oriented
from lab.synth import face_frame, manipulate


def auc(pos: list[float], neg: list[float]) -> float:
    """Rank-based AUC, ties averaged. No sklearn, no surprises."""
    pos, neg = np.asarray(pos, float), np.asarray(neg, float)
    if pos.size == 0 or neg.size == 0:
        return 0.5
    allv = np.concatenate([pos, neg])
    order = allv.argsort()
    ranks = np.empty_like(order, dtype=float)
    ranks[order] = np.arange(1, allv.size + 1)
    # average ranks for ties
    _, inv, counts = np.unique(allv, return_inverse=True, return_counts=True)
    sums = np.bincount(inv, weights=ranks)
    ranks = (sums / counts)[inv]
    r_pos = ranks[: pos.size].sum()
    return float((r_pos - pos.size * (pos.size + 1) / 2) / (pos.size * neg.size))


def roc_point(pos: list[float], neg: list[float], threshold: float) -> tuple[float, float]:
    tp = sum(1 for x in pos if x >= threshold)
    fp = sum(1 for x in neg if x >= threshold)
    return tp / max(1, len(pos)), fp / max(1, len(neg))


def best_threshold(pos: list[float], neg: list[float]) -> dict:
    best = {"threshold": 0.0, "tpr": 0.0, "fpr": 1.0, "j": -1.0}
    for t in sorted(set(pos) | set(neg)):
        tpr, fpr = roc_point(pos, neg, t)
        j = tpr - fpr
        if j > best["j"]:
            best = {"threshold": round(float(t), 4), "tpr": round(tpr, 3), "fpr": round(fpr, 3), "j": round(j, 3)}
    return best


def run(n: int = 24, seed: int = 20261105, levels: list[str] | None = None) -> dict:
    levels = levels or list(degrade.LEVELS)
    signals = list(all_signals(face_frame(0)).keys())
    out: dict = {"n_per_class": n, "seed": seed, "levels": {}}

    for level in levels:
        pos: dict[str, list[float]] = {s: [] for s in signals}
        neg: dict[str, list[float]] = {s: [] for s in signals}
        for i in range(n):
            auth = degrade.apply(face_frame(seed=i, size=256), level)
            fake = degrade.apply(manipulate(face_frame(seed=i, size=256), seed=i), level)
            for name, value in all_signals(fake).items():
                pos[name].append(oriented(name, value))
            for name, value in all_signals(auth).items():
                neg[name].append(oriented(name, value))
        out["levels"][level] = {
            name: {
                "auc": round(auc(pos[name], neg[name]), 3),
                "direction": __import__("lab.signals", fromlist=["DIRECTION"]).DIRECTION[name],
                "median_fake": round(float(np.median(pos[name])), 4),
                "median_authentic": round(float(np.median(neg[name])), 4),
                "operating_point": best_threshold(pos[name], neg[name]),
            }
            for name in signals
        }

    # The null control: shuffle labels and re-score. Anything above ~0.6 here is a leak.
    r = np.random.default_rng(seed)
    level = levels[-1]
    shuffled = []
    pos_all, neg_all = [], []
    for i in range(n):
        auth = degrade.apply(face_frame(seed=i, size=256), level)
        fake = degrade.apply(manipulate(face_frame(seed=i, size=256), seed=i), level)
        pos_all.append(oriented("noise_ratio", all_signals(fake)["noise_ratio"]))
        neg_all.append(oriented("noise_ratio", all_signals(auth)["noise_ratio"]))
    for _ in range(200):
        pool = np.array(pos_all + neg_all)
        r.shuffle(pool)
        shuffled.append(auc(list(pool[:n]), list(pool[n:])))
    out["null_control"] = {
        "signal": "noise_ratio",
        "level": level,
        "permutations": 200,
        "mean_auc": round(float(np.mean(shuffled)), 3),
        "p95_auc": round(float(np.percentile(shuffled, 95)), 3),
    }
    return out


def write_report(result: dict, path: str | Path) -> None:
    path = Path(path)
    lines = [
        "# Signal survival report",
        "",
        f"Generated by `python -m lab.experiment`. {result['n_per_class']} frames per class, "
        f"seed {result['seed']}. Synthetic corpus, ground-truth regions.",
        "",
        "AUC by degradation level. 0.5 is a coin flip: that signal died in the pipeline.",
        "",
        "| signal | " + " | ".join(result["levels"]) + " |",
        "| --- | " + " | ".join("---" for _ in result["levels"]) + " |",
    ]
    for name in result["levels"][next(iter(result["levels"]))]:
        row = [f"{result['levels'][lvl][name]['auc']:.2f}" for lvl in result["levels"]]
        lines.append(f"| {name} | " + " | ".join(row) + " |")
    lines += [
        "",
        "Operating point at the harshest level, with its cost attached:",
        "",
        "| signal | threshold | true positive | false positive |",
        "| --- | --- | --- | --- |",
    ]
    harsh = list(result["levels"])[-1]
    for name, data in result["levels"][harsh].items():
        op = data["operating_point"]
        lines.append(f"| {name} | {op['threshold']} | {op['tpr']:.0%} | {op['fpr']:.0%} |")
    null = result["null_control"]
    lines += [
        "",
        f"Null control: labels shuffled {null['permutations']} times on `{null['signal']}` at "
        f"`{null['level']}` gives mean AUC {null['mean_auc']}, p95 {null['p95_auc']}. A real signal "
        "must sit well outside that band.",
        "",
        "What this cannot tell you: whether a real generator leaves the same seam, whether real "
        "faces behave like these ovals, or how any of it performs on footage this lab did not make.",
    ]
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    res = run()
    write_report(res, "docs/lab-report.md")
    Path("docs/lab-result.json").write_text(json.dumps(res, indent=2) + "\n")
    print(json.dumps({lvl: {k: v["auc"] for k, v in d.items()} for lvl, d in res["levels"].items()}, indent=1))
    print("null:", res["null_control"])
